// Emit the circomlib Poseidon parameters (t = 3) and the empty-subtree hashes
// as Rust constants for crates/mixer-core.
//
// The on-chain hash must match circomlib's Poseidon(2) bit for bit, because the
// withdraw circuit recomputes the same Merkle tree. The round constants come
// straight from circomlibjs; the empty-subtree hashes are computed with
// circomlibjs' own reference implementation, and a Rust unit test recomputes
// them with the Rust implementation, which cross-checks the two.
//
// Usage: node scripts/gen-poseidon-constants.mjs   (from circuits/)
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildPoseidonReference } from "circomlibjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const circuits = path.join(here, "..");
const out = path.join(circuits, "..", "crates", "mixer-core", "src", "poseidon_constants.rs");

const T = 3; // state width for 2 inputs
const ROUNDS_F = 8;
const ROUNDS_P = 57;
const LEVELS = 20;

const constants = JSON.parse(
    readFileSync(path.join(circuits, "node_modules", "circomlibjs", "src", "poseidon_constants.json"), "utf8"),
);
const C = constants.C[T - 2].map((x) => BigInt(x));
const M = constants.M[T - 2].map((row) => row.map((x) => BigInt(x)));
if (C.length !== (ROUNDS_F + ROUNDS_P) * T) throw new Error(`unexpected C length ${C.length}`);
if (M.length !== T || M.some((row) => row.length !== T)) throw new Error("unexpected M shape");

const poseidon = await buildPoseidonReference();
const F = poseidon.F;
const hash2 = (a, b) => F.toObject(poseidon([a, b]));

const zeros = [0n];
for (let i = 0; i < LEVELS; i++) zeros.push(hash2(zeros[i], zeros[i]));

const fp = (x) => `MontFp!("${x.toString(10)}")`;
const lines = [];
lines.push("// @generated by circuits/scripts/gen-poseidon-constants.mjs. Do not edit.");
lines.push("//");
lines.push("// Poseidon parameters for BN254 Fr, t = 3 (two inputs), taken from circomlibjs");
lines.push(`// ${JSON.parse(readFileSync(path.join(circuits, "node_modules", "circomlibjs", "package.json"), "utf8")).version}.`);
lines.push("");
lines.push("use ark_bn254::Fr;");
lines.push("use ark_ff::MontFp;");
lines.push("");
lines.push(`pub const ROUNDS_F: usize = ${ROUNDS_F};`);
lines.push(`pub const ROUNDS_P: usize = ${ROUNDS_P};`);
lines.push("");
lines.push("/// Round constants, `C[round * 3 + i]` is added to state element `i`.");
lines.push(`pub static C: [Fr; ${C.length}] = [`);
for (const c of C) lines.push(`    ${fp(c)},`);
lines.push("];");
lines.push("");
lines.push("/// MDS matrix, `new[i] = sum_j M[i][j] * old[j]`.");
lines.push("pub static M: [[Fr; 3]; 3] = [");
for (const row of M) lines.push(`    [${row.map(fp).join(", ")}],`);
lines.push("];");
lines.push("");
lines.push("/// `ZEROS[i]` is the root of an empty subtree of height `i` (`ZEROS[0]` is the");
lines.push("/// empty leaf). Computed by circomlibjs, re-derived in the unit tests.");
lines.push(`pub static ZEROS: [Fr; ${LEVELS + 1}] = [`);
for (const z of zeros) lines.push(`    ${fp(z)},`);
lines.push("];");
lines.push("");
lines.push("/// circomlibjs reference outputs used as test vectors: `(a, b, poseidon([a, b]))`.");
const vectors = [
    [1n, 2n],
    [0n, 0n],
    [F.p - 1n, F.p - 2n],
    [123456789n, 987654321987654321n],
];
lines.push("#[cfg(test)]");
lines.push(`pub const TEST_VECTORS: [(Fr, Fr, Fr); ${vectors.length}] = [`);
for (const [a, b] of vectors) lines.push(`    (${fp(a)}, ${fp(b)}, ${fp(hash2(a, b))}),`);
lines.push("];");
lines.push("");

writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}`);
console.log(`poseidon([1, 2]) = ${hash2(1n, 2n)}`);
process.exit(0);
